#!/usr/bin/env python3
"""Builds assets/catalogue_ac.txt: the game item ids of the clothing of catalogue.ac.

catalogue.ac (The ULTIMATE Catalogue) identifies most items by their game id, in
decimal: "79" is item 0x004F. Clothing is the exception: one id per piece ("c652"),
and one game id per color, in order ("c652-1" is the second color). This script
keeps that table, and nothing else, from the site's data file:

    curl -o data.json https://catalogue.ac/data/data.json
    python3 tools/make_catalogue_ac.py data.json [--check]

Output lines: "c652 2542 14A9" = catalogue.ac id, then the game ids (hex) by color.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "catalogue_ac.txt"
CLOTHING = ("tops", "bottoms", "dresses", "hats", "accs", "socks", "shoes", "bags", "umbrellas", "wetsuits")


def build(data_path):
    d = json.load(open(data_path, encoding="utf-8"))
    names = (ROOT / "assets" / "items.txt").read_text(encoding="utf-8").split("\n")
    rows = []
    for cat in CLOTHING:
        for key, item in d["data"].get(cat, {}).items():
            if not key.startswith("c") or not key[1:].isdigit():
                continue
            ids = item.get("iid")
            ids = [ids] if isinstance(ids, int) else (ids or [])
            if not ids or not all(isinstance(i, int) and 0 <= i < len(names) and names[i] for i in ids):
                continue
            rows.append((int(key[1:]), "c%s %s" % (key[1:], " ".join("%04X" % i for i in ids))))
    rows.sort()
    head = ["# catalogue.ac clothing -> game item ids by color (hex), for lists imported from catalogue.ac.",
            "# Generated by tools/make_catalogue_ac.py from https://catalogue.ac/data/data.json (data of %s)." % d.get("date", "?")[:10],
            "# Other catalogue.ac ids are game ids already and need no table."]
    return "\n".join(head + [r[1] for r in rows]) + "\n", len(rows)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    text, n = build(sys.argv[1])
    if "--check" in sys.argv:
        ok = OUT.read_text(encoding="utf-8") == text
        print("catalogue_ac.txt matches the data" if ok else "catalogue_ac.txt differs from the data")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print("wrote %s: %d clothing items" % (OUT, n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
