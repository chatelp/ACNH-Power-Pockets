#!/usr/bin/env python3
"""Builds assets/item_stacks.txt: the largest stack the game allows for each item.

Source: NHSE (https://github.com/kwsch/NHSE, GPL-3.0), the same project items.txt
comes from. NHSE keeps the kind of every item (Resources/byte/item_kind.bin, one byte
per item id, dumped from the game's item table) and the largest stack of each kind
(ItemInfo.MaxCountByKind). This script joins the two.

Usage:
    python3 tools/make_item_stacks.py <NHSE checkout>       writes assets/item_stacks.txt
    python3 tools/make_item_stacks.py <NHSE checkout> --check   compares, writes nothing

Only three NHSE files are read, so a sparse download is enough:
    NHSE.Core/Structures/Item/ItemKind.cs
    NHSE.Core/Structures/Item/ItemInfo.cs
    NHSE.Core/Resources/byte/item_kind.bin
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ITEMS = os.path.join(ROOT, "assets", "items.txt")
OUT = os.path.join(ROOT, "assets", "item_stacks.txt")
NHSE_COMMIT = "cb0745415945776f73375bf0a434a8babf059307"

# Kinds NHSE leaves out of MaxCountByKind because its editor never needs their count:
# clothing and furniture never stack in the game. Picked flowers (UnitIcon_Flw*) count
# as Kind_Flower, exactly like NHSE's TryGetMaxStackCount does.
NEVER_STACK_PREFIXES = ("Top_", "Bottoms_", "Onepiece_", "Shoes_", "Kind_Shoes", "Ftr_")


def read(path, binary=False):
    with open(path, "rb" if binary else "r", **({} if binary else {"encoding": "utf-8-sig"})) as f:
        return f.read()


def kinds_enum(src):
    start = src.index("{", src.index("enum ItemKind"))
    body = src[start + 1:src.index("}", start)]
    kinds = []
    for ln in body.splitlines():
        ln = ln.split("//")[0].strip().rstrip(",")
        if not ln:
            continue
        if ln == "Unknown = byte.MaxValue":
            continue
        m = re.match(r"(\w+)(?:\s*=\s*(\d+))?$", ln)
        if not m:
            sys.exit("unexpected ItemKind line: %r" % ln)
        if m.group(2) is not None and int(m.group(2)) != len(kinds):
            sys.exit("ItemKind values are not sequential at %r" % ln)
        kinds.append(m.group(1))
    return kinds


def table(nhse):
    core = os.path.join(nhse, "NHSE.Core")
    kinds = kinds_enum(read(os.path.join(core, "Structures", "Item", "ItemKind.cs")))
    info = read(os.path.join(core, "Structures", "Item", "ItemInfo.cs"))
    by_kind = {k: int(v) for k, v in re.findall(r"\{(Kind_\w+),\s*(\d+)\}", info)}
    kind_of = read(os.path.join(core, "Resources", "byte", "item_kind.bin"), binary=True)
    names = read(ITEMS).split("\n")
    out, unknown = [], {}
    for i, name in enumerate(names):
        if not name or i >= len(kind_of):
            out.append(0)
            continue
        k = kinds[kind_of[i]]
        if k.startswith("UnitIcon_Flw"):
            k = "Kind_Flower"
        if k in by_kind:
            out.append(by_kind[k])
        elif k.startswith(NEVER_STACK_PREFIXES):
            out.append(1)
        else:
            out.append(0)
            unknown[k] = unknown.get(k, 0) + 1
    return out, unknown


def render(maxes, unknown):
    lines = [
        "# ACNH Power Pockets - largest stack the game allows for each item.",
        "# Copy this file to sdmc:/switch/acnh_power_pockets/ next to items.txt.",
        "#",
        "# Generated by tools/make_item_stacks.py from NHSE (github.com/kwsch/NHSE, GPL-3.0),",
        "# commit %s: item kinds (item_kind.bin) joined with" % NHSE_COMMIT,
        "# the largest stack of each kind (ItemInfo.MaxCountByKind). Clothing and furniture",
        "# never stack (1).",
        "#",
        "# Lines: <first id>[-<last id>] <largest stack>, ids in hex as in items.txt.",
        "# 1 = never stacks (shown as 1/slot). Ids not listed: unknown, the app falls back",
        "# to its other 1/slot rules and to the old 1..99 bound.",
    ]
    if unknown:
        lines.append("# Kinds with no known stack size: " +
                     ", ".join("%s (%d)" % kv for kv in sorted(unknown.items())))
    i = 0
    while i < len(maxes):
        v = maxes[i]
        j = i
        while j + 1 < len(maxes) and maxes[j + 1] == v:
            j += 1
        if v:
            lines.append(("%04X %d" % (i, v)) if i == j else ("%04X-%04X %d" % (i, j, v)))
        i = j + 1
    return "\n".join(lines) + "\n"


def main():
    args = sys.argv[1:]
    if not args or args[0].startswith("-"):
        sys.exit(__doc__)
    maxes, unknown = table(args[0])
    text = render(maxes, unknown)
    if "--check" in args:
        same = os.path.exists(OUT) and read(OUT) == text
        print("item_stacks.txt " + ("up to date" if same else "DIFFERS"))
        sys.exit(0 if same else 1)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    counts = {}
    for v in maxes:
        counts[v] = counts.get(v, 0) + 1
    print("wrote", OUT, {k: counts[k] for k in sorted(counts)})


if __name__ == "__main__":
    main()
